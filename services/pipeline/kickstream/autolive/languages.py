def _pack(rows: dict[str, str]) -> dict[str, str]:
    missing = [key for key in KEYS if key not in rows]
    extra = [key for key in rows if key not in KEYS]
    if missing or extra:
        raise RuntimeError(f"commentary phrases missing {missing} extra {extra}")
    return rows


